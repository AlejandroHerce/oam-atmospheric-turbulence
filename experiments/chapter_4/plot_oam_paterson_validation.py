"""
Visualize the weak-turbulence OAM-spectrum validation.

This script does not perform atmospheric propagation or recalculate
the OAM spectrum. It reads the results previously generated by

    weak_turbulence_oam_spectrum_validation.py

and compares the ensemble-averaged Split-Step spectrum with the
Paterson theoretical prediction.
"""

import argparse

from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np


# ============================================================
# Paths
# ============================================================

RESULTS_DIRECTORY = Path(
    "results/chapter_4/"
    "weak_turbulence_oam_spectrum_validation"
)

DEFAULT_INPUT_FILE = (
    RESULTS_DIRECTORY
    / "oam_spectrum_validation_summary.csv"
)

DEFAULT_OUTPUT_FILE = (
    RESULTS_DIRECTORY
    / "oam_spectrum_paterson_comparison.png"
)


# ============================================================
# Load saved validation
# ============================================================

def load_validation_results(
    filename: Path,
) -> tuple[
    np.ndarray,
    np.ndarray,
    np.ndarray,
    np.ndarray,
    np.ndarray,
]:
    """
    Load the OAM-spectrum validation summary.

    Expected CSV columns:

        ell
        split_step_mean
        ci95_lower
        ci95_upper
        paterson_theory
        absolute_difference
    """

    if not filename.exists():
        raise FileNotFoundError(
            f"Results file not found: {filename}"
        )

    data = np.genfromtxt(
        filename,
        delimiter=",",
        names=True,
        dtype=None,
        encoding="utf-8",
    )

    ell = np.asarray(
        data["ell"],
        dtype=np.int64,
    )

    numerical = np.asarray(
        data["split_step_mean"],
        dtype=np.float64,
    )

    lower = np.asarray(
        data["ci95_lower"],
        dtype=np.float64,
    )

    upper = np.asarray(
        data["ci95_upper"],
        dtype=np.float64,
    )

    theoretical = np.asarray(
        data["paterson_theory"],
        dtype=np.float64,
    )

    return (
        ell,
        numerical,
        lower,
        upper,
        theoretical,
    )


# ============================================================
# Automatic visual interval
# ============================================================

def determine_plot_interval(
    ell: np.ndarray,
    numerical: np.ndarray,
    upper: np.ndarray,
    theoretical: np.ndarray,
    threshold: float,
    padding: int,
) -> tuple[
    int,
    int,
]:
    """
    Find the OAM interval containing the visually relevant
    portion of either spectrum.

    This affects only visualization. The spectra themselves
    remain normalized over the full stored OAM interval.
    """

    relevant = (
        (numerical >= threshold)
        | (upper >= threshold)
        | (theoretical >= threshold)
    )

    indices = np.where(
        relevant
    )[0]

    if indices.size == 0:
        raise RuntimeError(
            "No modal components exceed the plotting threshold."
        )

    ell_min = int(
        ell[
            indices[0]
        ]
    )

    ell_max = int(
        ell[
            indices[-1]
        ]
    )

    return (
        max(
            int(ell[0]),
            ell_min - padding,
        ),
        min(
            int(ell[-1]),
            ell_max + padding,
        ),
    )


# ============================================================
# Plot
# ============================================================

def plot_validation(
    ell: np.ndarray,
    numerical: np.ndarray,
    lower: np.ndarray,
    upper: np.ndarray,
    theoretical: np.ndarray,
    output_file: Path,
    ell_min: int,
    ell_max: int,
    transmitted_ell: int = 1,
    logarithmic: bool = False,
) -> None:
    """
    Plot the saved Split-Step and Paterson OAM spectra.
    """

    mask = (
        (ell >= ell_min)
        & (ell <= ell_max)
    )

    if not np.any(
        mask
    ):
        raise ValueError(
            "Requested visual interval contains no OAM modes."
        )

    ell_plot = (
        ell[
            mask
        ]
    )

    numerical_plot = (
        numerical[
            mask
        ]
    )

    lower_plot = (
        lower[
            mask
        ]
    )

    upper_plot = (
        upper[
            mask
        ]
    )

    theoretical_plot = (
        theoretical[
            mask
        ]
    )

    figure, axis = plt.subplots(
        figsize=(8.0, 4.8)
    )

    # Numerical ensemble mean.
    axis.plot(
        ell_plot,
        numerical_plot,
        marker="o",
        linewidth=1.5,
        markersize=4,
        label="Split-Step",
    )

    # Ensemble uncertainty.
    axis.fill_between(
        ell_plot,
        lower_plot,
        upper_plot,
        alpha=0.2,
        label="IC 95 %",
    )

    # Independent theoretical reference.
    axis.plot(
        ell_plot,
        theoretical_plot,
        marker="s",
        markersize=4,
        linestyle="--",
        linewidth=1.5,
        label="Paterson",
    )

    # Transmitted state.
    axis.axvline(
        transmitted_ell,
        linestyle=":",
        linewidth=1.2,
        label=(
            rf"Modo transmitido "
            rf"$\ell_0={transmitted_ell}$"
        ),
    )

    if logarithmic:
        axis.set_yscale(
            "log"
        )

    axis.set_xlabel(
        r"Índice OAM $\ell$"
    )

    axis.set_ylabel(
        r"Potencia modal normalizada $P_\ell$"
    )

    axis.set_title(
        r"Validación del espectro OAM de $LG_0^1$"
    )

    axis.set_xlim(
        ell_min,
        ell_max,
    )

    axis.grid(
        alpha=0.3
    )

    axis.legend()

    figure.tight_layout()

    output_file.parent.mkdir(
        parents=True,
        exist_ok=True,
    )

    figure.savefig(
        output_file,
        dpi=300,
        bbox_inches="tight",
    )

    plt.close(
        figure
    )


# ============================================================
# CLI
# ============================================================

def parse_arguments() -> argparse.Namespace:

    parser = argparse.ArgumentParser()

    parser.add_argument(
        "--input",
        type=Path,
        default=DEFAULT_INPUT_FILE,
        help=(
            "Saved OAM validation summary CSV."
        ),
    )

    parser.add_argument(
        "--output",
        type=Path,
        default=DEFAULT_OUTPUT_FILE,
    )

    parser.add_argument(
        "--ell-min",
        type=int,
        default=None,
        help=(
            "Minimum displayed OAM index. "
            "If omitted, determined automatically."
        ),
    )

    parser.add_argument(
        "--ell-max",
        type=int,
        default=None,
        help=(
            "Maximum displayed OAM index. "
            "If omitted, determined automatically."
        ),
    )

    parser.add_argument(
        "--threshold",
        type=float,
        default=1.0e-4,
        help=(
            "Power threshold used to determine the "
            "automatic visual interval."
        ),
    )

    parser.add_argument(
        "--padding",
        type=int,
        default=3,
    )

    parser.add_argument(
        "--log",
        action="store_true",
        help=(
            "Use a logarithmic vertical axis."
        ),
    )

    return parser.parse_args()


# ============================================================
# Main
# ============================================================

def main() -> None:

    arguments = parse_arguments()

    (
        ell,
        numerical,
        lower,
        upper,
        theoretical,
    ) = load_validation_results(
        arguments.input
    )

    if (
        arguments.ell_min is None
        or arguments.ell_max is None
    ):

        (
            automatic_min,
            automatic_max,
        ) = determine_plot_interval(
            ell=ell,
            numerical=numerical,
            upper=upper,
            theoretical=theoretical,
            threshold=(
                arguments.threshold
            ),
            padding=(
                arguments.padding
            ),
        )

        ell_min = (
            automatic_min
            if arguments.ell_min is None
            else arguments.ell_min
        )

        ell_max = (
            automatic_max
            if arguments.ell_max is None
            else arguments.ell_max
        )

    else:

        ell_min = (
            arguments.ell_min
        )

        ell_max = (
            arguments.ell_max
        )

    print()

    print(
        "Visualización de la validación OAM"
    )

    print(
        "=================================="
    )

    print(
        f"Archivo: "
        f"{arguments.input}"
    )

    print(
        f"Intervalo almacenado: "
        f"[{ell[0]}, {ell[-1]}]"
    )

    print(
        f"Intervalo visual: "
        f"[{ell_min}, {ell_max}]"
    )

    plot_validation(
        ell=ell,
        numerical=numerical,
        lower=lower,
        upper=upper,
        theoretical=theoretical,
        output_file=(
            arguments.output
        ),
        ell_min=ell_min,
        ell_max=ell_max,
        logarithmic=(
            arguments.log
        ),
    )

    print()

    print(
        "Figura guardada en:"
    )

    print(
        arguments.output.resolve()
    )


if __name__ == "__main__":
    main()
