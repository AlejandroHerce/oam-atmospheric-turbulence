"""
Post-processing of the weak-turbulence Rytov validation.

This script reads the on-axis irradiance samples previously
generated by weak_turbulence_rytov_validation.py and performs
a bootstrap analysis of the numerical scintillation index.

No optical propagation is performed here.

Outputs:
    - numerical scintillation index
    - 95 % bootstrap confidence interval
    - analytical Rytov prediction
    - pointwise relative error
    - global relative L2 error
    - coverage of the Rytov prediction by the bootstrap interval
    - CSV table
    - final validation figure
"""

