"""
Aggregate Chapter 5 scenario results into a master summary table.

This script does not perform propagation or recalculate
realization-level quantities. It reads the results previously
generated by run_scenario.py and combines them into a single
scenario-level table suitable for later statistical analysis
and visualization.
"""

import argparse
import csv
import json

from pathlib import Path


# ============================================================
# Configuration
# ============================================================

RESULTS_ROOT = Path(
    "results/chapter_5"
)

DEFAULT_OUTPUT = (
    RESULTS_ROOT
    / "master_summary.csv"
)

VALID_REGIMES = (
    "weak",
    "moderate",
    "strong",
)

VALID_PSDS = (
    "kolmogorov",
    "von_karman",
    "modified_von_karman",
)

VALID_BEAMS = (
    "LG01",
    "LG02",
    "LG03",
    "BG01",
    "BG02",
    "BG03",
)


# ============================================================
# Beam utilities
# ============================================================

def beam_family(
    beam_name: str,
) -> str:
    """
    Return the beam family associated with one scenario.
    """

    if beam_name.startswith(
        "LG"
    ):
        return "LG"

    if beam_name.startswith(
        "BG"
    ):
        return "BG"

    raise ValueError(
        f"Unknown beam family: {beam_name}"
    )


# ============================================================
# Scenario discovery
# ============================================================

def discover_scenarios(
    results_root: Path,
) -> list[Path]:
    """
    Discover all saved Chapter 5 scenarios.

    A scenario is identified by the presence of metadata.json.
    """

    metadata_files = sorted(
        results_root.glob(
            "*/*/*/metadata.json"
        )
    )

    return [
        metadata_file.parent
        for metadata_file in metadata_files
    ]


# ============================================================
# Metadata loading
# ============================================================

def load_metadata(
    scenario_directory: Path,
) -> dict:
    """
    Load scenario metadata.
    """

    filename = (
        scenario_directory
        / "metadata.json"
    )

    if not filename.exists():
        raise FileNotFoundError(
            f"Missing metadata: {filename}"
        )

    with filename.open(
        "r",
        encoding="utf-8",
    ) as file:

        metadata = json.load(
            file
        )

    return metadata


# ============================================================
# Summary loading
# ============================================================

def load_summary(
    scenario_directory: Path,
) -> list[dict]:
    """
    Load all rows from one scenario summary.csv.
    """

    filename = (
        scenario_directory
        / "summary.csv"
    )

    if not filename.exists():
        raise FileNotFoundError(
            f"Missing summary: {filename}"
        )

    with filename.open(
        "r",
        newline="",
        encoding="utf-8",
    ) as file:

        reader = csv.DictReader(
            file
        )

        rows = [
            dict(
                row
            )
            for row in reader
        ]

    return rows


# ============================================================
# Summary row lookup
# ============================================================

def find_summary_row(
    rows: list[dict],
    metric: str,
    calculation: str,
) -> dict:
    """
    Find exactly one summary row matching metric and calculation.
    """

    matches = [
        row
        for row in rows
        if (
            row["metric"] == metric
            and row["calculation"] == calculation
        )
    ]

    if len(matches) != 1:
        raise RuntimeError(
            "Expected exactly one summary row for "
            f"metric={metric}, calculation={calculation}; "
            f"found {len(matches)}."
        )

    return matches[0]


# ============================================================
# Scalar conversion
# ============================================================

def optional_float(
    value: str,
) -> float | None:
    """
    Convert a CSV field to float, preserving empty fields as None.
    """

    if value is None:
        return None

    stripped = value.strip()

    if stripped == "":
        return None

    return float(
        stripped
    )


# ============================================================
# Scenario extraction
# ============================================================

def extract_scenario_record(
    scenario_directory: Path,
) -> dict:
    """
    Convert one scenario directory into one master-table record.
    """

    metadata = load_metadata(
        scenario_directory
    )

    summary_rows = load_summary(
        scenario_directory
    )

    beam = str(
        metadata["beam"]
    )

    psd = str(
        metadata["psd"]
    )

    regime = str(
        metadata["regime"]
    )

    transmitted_ell = int(
        metadata["transmitted_ell"]
    )

    number_of_realizations = int(
        metadata[
            "number_of_realizations"
        ]
    )

    # --------------------------------------------------------
    # Ensemble mean of realization-level modal metrics
    # --------------------------------------------------------

    retention_ensemble = (
        find_summary_row(
            rows=summary_rows,
            metric="retention",
            calculation="ensemble_mean_of_metric",
        )
    )

    spread_ensemble = (
        find_summary_row(
            rows=summary_rows,
            metric="oam_rms_spread",
            calculation="ensemble_mean_of_metric",
        )
    )

    entropy_ensemble = (
        find_summary_row(
            rows=summary_rows,
            metric="normalized_oam_entropy",
            calculation="ensemble_mean_of_metric",
        )
    )

    # --------------------------------------------------------
    # Beam wander
    # --------------------------------------------------------

    beam_wander = (
        find_summary_row(
            rows=summary_rows,
            metric="beam_wander_rms_m",
            calculation="ensemble_statistic",
        )
    )

    # --------------------------------------------------------
    # Total power
    # --------------------------------------------------------

    total_power = (
        find_summary_row(
            rows=summary_rows,
            metric="total_power",
            calculation="ensemble_mean_of_metric",
        )
    )

    # --------------------------------------------------------
    # Metrics of ensemble-averaged OAM spectrum
    # --------------------------------------------------------

    retention_mean_spectrum = (
        find_summary_row(
            rows=summary_rows,
            metric="retention",
            calculation="metric_of_mean_spectrum",
        )
    )

    spread_mean_spectrum = (
        find_summary_row(
            rows=summary_rows,
            metric="oam_rms_spread",
            calculation="metric_of_mean_spectrum",
        )
    )

    entropy_mean_spectrum = (
        find_summary_row(
            rows=summary_rows,
            metric="normalized_oam_entropy",
            calculation="metric_of_mean_spectrum",
        )
    )

    # --------------------------------------------------------
    # Build flat master record
    # --------------------------------------------------------

    return {
        "beam":
            beam,

        "family":
            beam_family(
                beam
            ),

        "transmitted_ell":
            transmitted_ell,

        "psd":
            psd,

        "regime":
            regime,

        "number_of_realizations":
            number_of_realizations,

        # ----------------------------------------------------
        # Turbulence metadata
        # ----------------------------------------------------

        "r0_total_m":
            float(
                metadata[
                    "r0_total_m"
                ]
            ),

        "r0_screen_m":
            float(
                metadata[
                    "r0_screen_m"
                ]
            ),

        "outer_scale_m":
            metadata.get(
                "outer_scale_m"
            ),

        "inner_scale_m":
            metadata.get(
                "inner_scale_m"
            ),

        "subharmonic_level":
            int(
                metadata[
                    "subharmonic_level"
                ]
            ),

        # ----------------------------------------------------
        # Retention:
        # ensemble mean of realization metric
        # ----------------------------------------------------

        "retention_mean":
            float(
                retention_ensemble[
                    "estimate"
                ]
            ),

        "retention_std":
            optional_float(
                retention_ensemble[
                    "sample_std"
                ]
            ),

        "retention_ci95_lower":
            float(
                retention_ensemble[
                    "ci95_lower"
                ]
            ),

        "retention_ci95_upper":
            float(
                retention_ensemble[
                    "ci95_upper"
                ]
            ),

        # ----------------------------------------------------
        # OAM RMS spread:
        # ensemble mean of realization metric
        # ----------------------------------------------------

        "oam_spread_mean":
            float(
                spread_ensemble[
                    "estimate"
                ]
            ),

        "oam_spread_std":
            optional_float(
                spread_ensemble[
                    "sample_std"
                ]
            ),

        "oam_spread_ci95_lower":
            float(
                spread_ensemble[
                    "ci95_lower"
                ]
            ),

        "oam_spread_ci95_upper":
            float(
                spread_ensemble[
                    "ci95_upper"
                ]
            ),

        # ----------------------------------------------------
        # Normalized entropy:
        # ensemble mean of realization metric
        # ----------------------------------------------------

        "entropy_mean":
            float(
                entropy_ensemble[
                    "estimate"
                ]
            ),

        "entropy_std":
            optional_float(
                entropy_ensemble[
                    "sample_std"
                ]
            ),

        "entropy_ci95_lower":
            float(
                entropy_ensemble[
                    "ci95_lower"
                ]
            ),

        "entropy_ci95_upper":
            float(
                entropy_ensemble[
                    "ci95_upper"
                ]
            ),

        # ----------------------------------------------------
        # Beam wander
        # ----------------------------------------------------

        "beam_wander_rms_m":
            float(
                beam_wander[
                    "estimate"
                ]
            ),

        "beam_wander_ci95_lower_m":
            float(
                beam_wander[
                    "ci95_lower"
                ]
            ),

        "beam_wander_ci95_upper_m":
            float(
                beam_wander[
                    "ci95_upper"
                ]
            ),

        # ----------------------------------------------------
        # Power diagnostic
        # ----------------------------------------------------

        "mean_total_power":
            float(
                total_power[
                    "estimate"
                ]
            ),

        "std_total_power":
            optional_float(
                total_power[
                    "sample_std"
                ]
            ),

        # ----------------------------------------------------
        # Metrics of ensemble-averaged spectrum
        # ----------------------------------------------------

        "retention_from_mean_spectrum":
            float(
                retention_mean_spectrum[
                    "estimate"
                ]
            ),

        "oam_spread_from_mean_spectrum":
            float(
                spread_mean_spectrum[
                    "estimate"
                ]
            ),

        "oam_spread_mean_spectrum_ci95_lower":
            float(
                spread_mean_spectrum[
                    "ci95_lower"
                ]
            ),

        "oam_spread_mean_spectrum_ci95_upper":
            float(
                spread_mean_spectrum[
                    "ci95_upper"
                ]
            ),

        "entropy_from_mean_spectrum":
            float(
                entropy_mean_spectrum[
                    "estimate"
                ]
            ),

        "entropy_mean_spectrum_ci95_lower":
            float(
                entropy_mean_spectrum[
                    "ci95_lower"
                ]
            ),

        "entropy_mean_spectrum_ci95_upper":
            float(
                entropy_mean_spectrum[
                    "ci95_upper"
                ]
            ),

        # ----------------------------------------------------
        # Source path for traceability
        # ----------------------------------------------------

        "scenario_directory":
            str(
                scenario_directory
            ),
    }


# ============================================================
# Filters
# ============================================================

def scenario_matches_filters(
    record: dict,
    beam: str | None,
    psd: str | None,
    regime: str | None,
) -> bool:
    """
    Test whether one master record satisfies CLI filters.
    """

    if (
        beam is not None
        and record[
            "beam"
        ] != beam
    ):
        return False

    if (
        psd is not None
        and record[
            "psd"
        ] != psd
    ):
        return False

    if (
        regime is not None
        and record[
            "regime"
        ] != regime
    ):
        return False

    return True


# ============================================================
# Sorting
# ============================================================

def sort_key(
    record: dict,
) -> tuple:
    """
    Define a stable scientific ordering of scenarios.
    """

    regime_order = {
        "weak": 0,
        "moderate": 1,
        "strong": 2,
    }

    psd_order = {
        "kolmogorov": 0,
        "von_karman": 1,
        "modified_von_karman": 2,
    }

    family_order = {
        "LG": 0,
        "BG": 1,
    }

    return (
        regime_order[
            record["regime"]
        ],
        family_order[
            record["family"]
        ],
        record[
            "transmitted_ell"
        ],
        psd_order[
            record["psd"]
        ],
    )


# ============================================================
# Save master table
# ============================================================

def save_master_summary(
    records: list[dict],
    output_file: Path,
) -> None:
    """
    Save one row per Chapter 5 scenario.
    """

    if len(records) == 0:
        raise ValueError(
            "No scenario records to save."
        )

    output_file.parent.mkdir(
        parents=True,
        exist_ok=True,
    )

    fieldnames = list(
        records[0].keys()
    )

    with output_file.open(
        "w",
        newline="",
        encoding="utf-8",
    ) as file:

        writer = csv.DictWriter(
            file,
            fieldnames=fieldnames,
        )

        writer.writeheader()

        writer.writerows(
            records
        )


# ============================================================
# Terminal summary
# ============================================================

def print_records(
    records: list[dict],
) -> None:
    """
    Print a compact scenario table for quick inspection.
    """

    print()

    print(
        "Chapter 5 master summary"
    )

    print(
        "=" * 112
    )

    header = (
        f"{'Beam':>6} "
        f"{'PSD':>22} "
        f"{'Regime':>9} "
        f"{'N':>6} "
        f"{'<R>':>10} "
        f"{'<sigma_l>':>12} "
        f"{'<H>':>10} "
        f"{'BW [mm]':>11}"
    )

    print(
        header
    )

    print(
        "-" * len(
            header
        )
    )

    for record in records:

        print(
            f"{record['beam']:>6} "
            f"{record['psd']:>22} "
            f"{record['regime']:>9} "
            f"{record['number_of_realizations']:6d} "
            f"{record['retention_mean']:10.5f} "
            f"{record['oam_spread_mean']:12.5f} "
            f"{record['entropy_mean']:10.5f} "
            f"{1.0e3 * record['beam_wander_rms_m']:11.5f}"
        )


# ============================================================
# CLI
# ============================================================

def parse_arguments() -> argparse.Namespace:

    parser = argparse.ArgumentParser()

    parser.add_argument(
        "--beam",
        choices=VALID_BEAMS,
        default=None,
    )

    parser.add_argument(
        "--psd",
        choices=VALID_PSDS,
        default=None,
    )

    parser.add_argument(
        "--regime",
        choices=VALID_REGIMES,
        default=None,
    )

    parser.add_argument(
        "--output",
        type=Path,
        default=DEFAULT_OUTPUT,
    )

    return parser.parse_args()


# ============================================================
# Main
# ============================================================

def main() -> None:

    arguments = parse_arguments()

    scenario_directories = (
        discover_scenarios(
            RESULTS_ROOT
        )
    )

    if len(
        scenario_directories
    ) == 0:
        raise RuntimeError(
            "No Chapter 5 scenarios were found."
        )

    records = []

    for scenario_directory in (
        scenario_directories
    ):

        record = (
            extract_scenario_record(
                scenario_directory
            )
        )

        if scenario_matches_filters(
            record=record,
            beam=arguments.beam,
            psd=arguments.psd,
            regime=arguments.regime,
        ):

            records.append(
                record
            )

    records.sort(
        key=sort_key
    )

    if len(records) == 0:
        raise RuntimeError(
            "No scenarios matched the requested filters."
        )

    save_master_summary(
        records=records,
        output_file=arguments.output,
    )

    print_records(
        records
    )

    print()

    print(
        f"Scenarios included: "
        f"{len(records)}"
    )

    print(
        "Master summary saved in:"
    )

    print(
        arguments.output.resolve()
    )


if __name__ == "__main__":
    main()
